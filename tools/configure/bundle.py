"""Single-writer publication of owned configuration bundles.

Old public output is withdrawn before resolution. An interrupted writer leaves
only a private owned backup; the next writer may remove it under the same lock.
Unchanged generated bytes inherit their old timestamp for incremental builds.
"""
from contextlib import contextmanager
import json
import os
from pathlib import Path
import shutil


def _regular(path):
    return path.is_file() and not path.is_symlink()


def _protect(output, inputs, fail):
    for value in inputs:
        source = Path(value).resolve()
        if output == source or output in source.parents:
            fail(f"Configuration output must not replace input: {source}")


def _navigation(directory):
    path = directory / "input_paths.json"
    if not _regular(path):
        return ()
    try:
        records = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return ()
    return tuple(value for value in records.values() if isinstance(value, str))


@contextmanager
def _writer_lock(output, fail):
    # Never unlink a lock inode: a waiting writer must share it with its owner.
    path = output.parent / ("." + output.name + ".nexus-lock")
    if path.is_symlink() or (path.exists() and not path.is_file()):
        fail("Configuration writer lock must be a regular file")
    flags = os.O_RDWR | os.O_CREAT | getattr(os, "O_NOFOLLOW", 0)
    descriptor = os.open(path, flags, 0o600)
    acquired = False
    try:
        if os.name == "nt":
            import msvcrt
            if os.fstat(descriptor).st_size == 0:
                os.write(descriptor, b"\0")
            os.lseek(descriptor, 0, os.SEEK_SET)
            try:
                msvcrt.locking(descriptor, msvcrt.LK_NBLCK, 1)
            except OSError:
                fail(f"Output is already being configured: {output}")
        else:
            import fcntl
            try:
                fcntl.flock(descriptor, fcntl.LOCK_EX | fcntl.LOCK_NB)
            except BlockingIOError:
                fail(f"Output is already being configured: {output}")
        acquired = True
        yield
    finally:
        if acquired and os.name == "nt":
            import msvcrt
            os.lseek(descriptor, 0, os.SEEK_SET)
            msvcrt.locking(descriptor, msvcrt.LK_UNLCK, 1)
        os.close(descriptor)


def _owned(directory, marker, fail):
    if (directory.is_symlink() or not directory.is_dir() or
            not _regular(directory / marker)):
        fail(f"Existing output is not an owned configuration bundle: {directory}")
    # Generated bundles are flat regular-file sets. Ownership cannot authorize
    # following a newly inserted symlink or erasing a foreign nested directory.
    if any(not _regular(path) for path in directory.iterdir()):
        fail(f"Owned configuration bundle contains foreign entries: {directory}")


@contextmanager
def transaction(output, marker, *, inputs, fail, packages=()):
    """Yield a fresh directory, then publish it atomically or withdraw output."""
    output = Path(os.path.abspath(output))
    inputs, packages = tuple(inputs), tuple(packages)
    if any(path.is_symlink() for path in (output, *output.parents)):
        fail("Configuration output path must not contain a symlink")
    if output == output.parent:
        fail("Unsafe configuration output directory")
    _protect(output, inputs, fail)
    for value in packages:
        directory = Path(value).resolve()
        if output.is_relative_to(directory) or directory.is_relative_to(output):
            fail(f"Configuration output must not overlap input package: {directory}")
    output.parent.mkdir(parents=True, exist_ok=True)
    backup = output.parent / ("." + output.name + ".nexus-previous")
    pending = output.parent / ("." + output.name + ".nexus-pending")
    pending_owner = output.parent / ("." + output.name + ".nexus-pending-owner")
    owner_bytes = ("Nexus pending bundle " + marker + "\n").encode()
    with _writer_lock(output, fail):
        for directory in (output, backup):
            _protect(directory, inputs, fail)
            if directory.exists() or directory.is_symlink():
                _owned(directory, marker, fail)
                _protect(output, _navigation(directory), fail)
                _protect(directory, _navigation(directory), fail)
        _protect(pending, inputs, fail)
        _protect(pending_owner, inputs, fail)
        if pending_owner.exists() or pending_owner.is_symlink():
            if (not _regular(pending_owner) or
                    pending_owner.read_bytes() != owner_bytes):
                fail("Pending configuration ownership record is invalid")
        if pending.exists() or pending.is_symlink():
            if (not pending_owner.is_file() or pending.is_symlink() or
                    not pending.is_dir() or
                    any(not _regular(path) for path in pending.iterdir())):
                fail("Pending configuration is not an owned bundle")
            _protect(pending, _navigation(pending), fail)
            shutil.rmtree(pending)
        pending_owner.unlink(missing_ok=True)
        if backup.exists():
            shutil.rmtree(backup)
        if output.exists():
            os.replace(output, backup)
        temporary = None
        try:
            temporary = pending
            pending_owner.write_bytes(owner_bytes)
            temporary.mkdir()
            yield temporary
            _owned(temporary, marker, fail)
            if backup.exists():
                for target in temporary.iterdir():
                    previous = backup / target.name
                    if (_regular(previous) and
                            previous.read_bytes() == target.read_bytes()):
                        old = previous.stat()
                        os.utime(target, ns=(old.st_atime_ns, old.st_mtime_ns))
            os.replace(temporary, output)
            if backup.exists():
                shutil.rmtree(backup)
            pending_owner.unlink(missing_ok=True)
            temporary = None
        except BaseException:
            # Even a publication/cleanup error must not report rejection while
            # leaving a seemingly successful new public bundle behind.
            if output.exists():
                shutil.rmtree(output)
            raise
        finally:
            if temporary is not None:
                shutil.rmtree(temporary, ignore_errors=True)
            if backup.exists():
                shutil.rmtree(backup)
            pending_owner.unlink(missing_ok=True)
